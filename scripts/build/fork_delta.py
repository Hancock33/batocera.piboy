#!/usr/bin/env python3
"""Regenerate the generated part of FORK.md: how this fork's package and
board lists differ from upstream Batocera.

Compares the committed trees of two refs, so nothing needs to be checked out:

    git fetch upstream
    scripts/build/fork_delta.py            # HEAD against its merge-base with upstream/master
    scripts/build/fork_delta.py --tip      # HEAD against upstream/master itself
    scripts/build/fork_delta.py --upstream some/ref --fork some/other/ref

Only the text between the BEGIN/END markers in FORK.md is rewritten; anything
outside them is kept as written.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FORK_MD = ROOT / 'FORK.md'
BEGIN = '<!-- BEGIN generated by scripts/build/fork_delta.py -->'
END = '<!-- END generated -->'
RE_PACKAGE = re.compile(r'^((?:package|python-src)/.+)/([^/]+)/\2\.mk$')
RE_BOARD = re.compile(r'^configs/([^/]+)\.board$')


def git(*args: str) -> str:
    return subprocess.run(['git', '-C', str(ROOT), *args], check=True, capture_output=True, text=True).stdout


def tree(ref: str) -> list[str]:
    return git('ls-tree', '-r', '--name-only', ref).splitlines()


def packages(files: list[str]) -> dict[str, str]:
    """Package name -> category (its path below package/batocera)."""
    found: dict[str, str] = {}
    for path in files:
        match = RE_PACKAGE.match(path)
        if match:
            parent = match.group(1).removeprefix('package/batocera/').removeprefix('package/')
            found[match.group(2)] = parent
    return found


def boards(files: list[str]) -> set[str]:
    return {m.group(1).removeprefix('batocera-') for m in map(RE_BOARD.match, files) if m}


def table(names: set[str], where: dict[str, str]) -> list[str]:
    groups: dict[str, list[str]] = defaultdict(list)
    for name in names:
        groups[where[name]].append(name)
    lines = ['| Category | Packages |', '| --- | --- |']
    lines += [f'| `{category}` | {", ".join(sorted(groups[category]))} |' for category in sorted(groups)]
    return lines


def generate(fork_ref: str, upstream_ref: str) -> str:
    fork_files, upstream_files = tree(fork_ref), tree(upstream_ref)
    fork, upstream = packages(fork_files), packages(upstream_files)
    only_fork, only_upstream = set(fork) - set(upstream), set(upstream) - set(fork)
    fork_boards, upstream_boards = boards(fork_files), boards(upstream_files)
    upstream_sha = git('rev-parse', '--short', upstream_ref).strip()
    upstream_date = git('log', '-1', '--format=%cs', upstream_ref).strip()

    lines = [
        BEGIN,
        '',
        f'Compared with upstream `{upstream_sha}` ({upstream_date}). '
        f'The fork has {len(fork)} packages and upstream has {len(upstream)}.',
        '',
        '## Boards',
        '',
        f'Built here: {", ".join(sorted(fork_boards)) or "none"}.',
        '',
        f'Upstream boards with no config at the top level here: {", ".join(sorted(upstream_boards - fork_boards)) or "none"}.',
        '',
        f'## Packages only in this fork ({len(only_fork)})',
        '',
        *table(only_fork, fork),
        '',
        f'## Upstream packages not in this fork ({len(only_upstream)})',
        '',
        'Upstream changes to these arrive as modify/delete conflicts when merging.',
        '',
        *table(only_upstream, upstream),
        '',
        END,
    ]
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description='Regenerate the generated part of FORK.md')
    parser.add_argument('--fork', default='HEAD', help='ref of this fork (default: HEAD)')
    parser.add_argument('--upstream', default='upstream/master', help='ref of upstream (default: upstream/master)')
    parser.add_argument(
        '--tip',
        action='store_true',
        help='compare with the upstream ref itself, not with its merge-base with the fork',
    )
    parser.add_argument('--check', action='store_true', help='exit 1 if FORK.md is out of date, without writing')
    args = parser.parse_args()

    try:
        # The merge-base is the upstream commit last merged, so the result does not
        # change every time upstream moves on and --check stays usable in CI.
        upstream = args.upstream if args.tip else git('merge-base', args.fork, args.upstream).strip()
        block = generate(args.fork, upstream)
    except subprocess.CalledProcessError as error:
        print(error.stderr.strip() or error, file=sys.stderr)
        return 2

    # newline='' / '\n': no newline translation, so FORK.md keeps Unix line endings on Windows
    raw = ''
    if FORK_MD.is_file():
        with FORK_MD.open(encoding='utf-8', newline='') as file:
            raw = file.read()
    current = raw.replace('\r\n', '\n')
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        updated = head + block + rest.split(END, 1)[1]
    else:
        updated = current.rstrip('\n') + ('\n\n' if current.strip() else '') + block + '\n'

    if args.check:
        return 0 if updated == raw else 1
    FORK_MD.write_text(updated, encoding='utf-8', newline='\n')
    print(f'updated {FORK_MD.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
